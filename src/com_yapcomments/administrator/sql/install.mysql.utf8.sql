CREATE TABLE IF NOT EXISTS `#__yapcomments_comments` (
  `id` int unsigned NOT NULL AUTO_INCREMENT,
  `context` varchar(100) NOT NULL DEFAULT '',
  `item_id` int unsigned NOT NULL DEFAULT 0,
  `parent_id` int unsigned NOT NULL DEFAULT 0,
  `root_id` int unsigned NOT NULL DEFAULT 0,
  `depth` tinyint unsigned NOT NULL DEFAULT 0,
  `user_id` int unsigned NOT NULL DEFAULT 0,
  `name` varchar(100) NOT NULL DEFAULT '',
  `email` varchar(150) NOT NULL DEFAULT '',
  `body` mediumtext NOT NULL,
  `flags` int unsigned NOT NULL DEFAULT 0,
  `state` tinyint NOT NULL DEFAULT 1,
  `pinned` tinyint NOT NULL DEFAULT 0,
  `likes` int unsigned NOT NULL DEFAULT 0,
  `dislikes` int unsigned NOT NULL DEFAULT 0,
  `ip` varchar(64) NOT NULL DEFAULT '',
  `user_agent` varchar(255) NOT NULL DEFAULT '',
  `item_title` varchar(255) NOT NULL DEFAULT '',
  `item_url` varchar(1024) NOT NULL DEFAULT '',
  `language` char(7) NOT NULL DEFAULT '*',
  `created` datetime NOT NULL,
  `modified` datetime NULL DEFAULT NULL,
  `modified_by` int unsigned NOT NULL DEFAULT 0,
  `edit_count` int unsigned NOT NULL DEFAULT 0,
  `checked_out` int unsigned,
  `checked_out_time` datetime NULL DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `idx_item` (`context`, `item_id`, `state`, `parent_id`),
  KEY `idx_root` (`root_id`),
  KEY `idx_parent` (`parent_id`),
  KEY `idx_user` (`user_id`),
  KEY `idx_state_created` (`state`, `created`),
  KEY `idx_ip_created` (`ip`, `created`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 DEFAULT COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `#__yapcomments_votes` (
  `comment_id` int unsigned NOT NULL,
  `voter` varchar(64) NOT NULL,
  `user_id` int unsigned NOT NULL DEFAULT 0,
  `vote` tinyint NOT NULL,
  `created` datetime NOT NULL,
  PRIMARY KEY (`comment_id`, `voter`),
  KEY `idx_user` (`user_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 DEFAULT COLLATE=utf8mb4_unicode_ci;
