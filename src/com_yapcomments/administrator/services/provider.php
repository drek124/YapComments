\defined('_JEXEC') or die;

use Drek124\Component\YapComments\Administrator\Extension\YapCommentsComponent;
use Joomla\CMS\Dispatcher\ComponentDispatcherFactoryInterface;
use Joomla\CMS\Extension\ComponentInterface;
use Joomla\CMS\Extension\Service\Provider\ComponentDispatcherFactory;
use Joomla\CMS\Extension\Service\Provider\MVCFactory;
use Joomla\CMS\MVC\Factory\MVCFactoryInterface;
use Joomla\DI\Container;
use Joomla\DI\ServiceProviderInterface;

return new class () implements ServiceProviderInterface {
    public function register(Container $container): void
    {
        $container->registerServiceProvider(new MVCFactory('\\Drek124\\Component\\YapComments'));
        $container->registerServiceProvider(new ComponentDispatcherFactory('\\Drek124\\Component\\YapComments'));

        $container->set(
            ComponentInterface::class,
            function (Container $container) {
                $component = new YapCommentsComponent($container->get(ComponentDispatcherFactoryInterface::class));
                $component->setMVCFactory($container->get(MVCFactoryInterface::class));

                return $component;
            }
        );
    }
};
